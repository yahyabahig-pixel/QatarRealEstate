    /// <summary>
    /// Deterministic, process-stable index into a list. Deliberately NOT string.GetHashCode:
    /// that is randomised per process, so the same title would map to a different agent on
    /// every restart.
    /// </summary>
    private static int StableIndex(string value, int modulo)
    {
        unchecked
        {
            var hash = 17;
            foreach (var ch in value)
                hash = (hash * 31) + ch;

            return (hash & 0x7FFFFFFF) % modulo;
        }
    }

    private static SaleTerms BuildSaleTerms(
        string title, decimal salePrice, string currency,
        PaymentMethod paymentMethod, InstallmentSeed? installment)
    {
        var price = Must(Money.Create(salePrice, currency), $"sale price of '{title}'");

        InstallmentPlan? plan = null;
        if (paymentMethod == PaymentMethod.Installment)
        {
            if (installment is null)
                throw new InvalidOperationException(
                    $"Seed failed: listing '{title}' uses PaymentMethod.Installment " +
                    "but has no Installment block in its seed catalog.");

            var down = Must(Money.Create(installment.DownPayment, currency),
                            $"down payment of '{title}'");
            var each = Must(Money.Create(installment.InstallmentAmount, currency),
                            $"installment amount of '{title}'");

            plan = Must(
                InstallmentPlan.Create(down, installment.NumberOfInstallments, each,
                                       installment.Frequency),
                $"installment plan of '{title}'");
        }

        return Must(SaleTerms.Create(price, paymentMethod, plan), $"sale terms of '{title}'");
    }

    private static RentTerms BuildRentTerms(
        string title, decimal rentPrice, string currency, int contractDurationMonths)
    {
        var price = Must(Money.Create(rentPrice, currency), $"rent price of '{title}'");
        return Must(RentTerms.Create(price, contractDurationMonths), $"rent terms of '{title}'");
    }

    /// <summary>Unwraps a domain factory result or fails loudly — seed data must never be invalid.</summary>
    private static T Must<T>(Result<T> result, string what)
    {
        if (result.IsError)
        {
            var error = result.TopError;
            throw new InvalidOperationException(
                $"Seed failed building {what}: [{error.Code}] {error.Description}");
        }

        return result.Value;
    }

    private static void MustSucceed(Result<Updated> result, string what)
    {
        if (result.IsError)
        {
            var error = result.TopError;
            throw new InvalidOperationException(
                $"Seed failed while {what}: [{error.Code}] {error.Description}");
        }
    }
